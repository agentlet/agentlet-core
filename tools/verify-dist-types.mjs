#!/usr/bin/env node
/**
 * Cheap guard rail for dist/agentlet-core.d.ts.
 *
 * src/types/public-api.d.ts is hand-written and copied as-is to
 * dist/agentlet-core.d.ts by tools/build.js (see copyTypeDeclarations()).
 * tests/types/public-api.test-d.ts (checked by `npm run typecheck`)
 * verifies the SOURCE file against the real implementation, but nothing
 * else exercises the file that actually ships in dist/ after the copy.
 *
 * This script compiles a small standalone consumer file against
 * dist/agentlet-core.d.ts, the same way a real TypeScript agentlet
 * consumes the published types (see docs/typescript.md). It is not a
 * replacement for tests/types/public-api.test-d.ts - it only catches a
 * dist/agentlet-core.d.ts that fails to parse, load, or resolve once
 * built and packaged (a broken copy step, a stale file left over from a
 * previous build, etc).
 *
 * Run standalone with `npm run verify:dist-types` (after `npm run build`),
 * or automatically at the end of `node tools/build.js` / `npm run build`.
 */

import { spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.join(__dirname, '..');
const distDts = path.join(rootDir, 'dist', 'agentlet-core.d.ts');

function fail(message) {
    console.error(`❌ ${message}`);
    process.exit(1);
}

if (!existsSync(distDts)) {
    fail(`dist/agentlet-core.d.ts not found at ${distDts}. Run \`npm run build\` first.`);
}

// Module specifier without the .d.ts extension: TypeScript resolves
// "<dir>/agentlet-core" to "<dir>/agentlet-core.d.ts" the same way it would
// resolve a real package's "types" entry (see package.json).
const distModuleSpecifier = path.join(rootDir, 'dist', 'agentlet-core').replace(/\\/g, '/');

const consumerSource = `// Auto-generated by tools/verify-dist-types.mjs - not part of the source tree.
import type { AgentletAPI, ModuleActivationContext } from ${JSON.stringify(distModuleSpecifier)};

declare const agentlet: AgentletAPI;

function handleActivation(context: ModuleActivationContext): void {
    console.log(context.trigger);
}

void agentlet.ai.isAvailable();
void agentlet.forms.quickExport;
void agentlet.tables.extract;
void agentlet.utils.Dialog;
void handleActivation;
`;

const tmpDir = mkdtempSync(path.join(tmpdir(), 'agentlet-dist-types-'));
const consumerFile = path.join(tmpDir, 'consumer.ts');

try {
    writeFileSync(consumerFile, consumerSource, 'utf8');

    const tscBin = path.join(rootDir, 'node_modules', '.bin', 'tsc');
    const tscArgs = [
        '--noEmit',
        '--strict',
        '--target', 'ES2020',
        '--module', 'ESNext',
        '--moduleResolution', 'bundler',
        '--lib', 'DOM,DOM.Iterable,ES2022',
        '--skipLibCheck',
        consumerFile
    ];

    console.log('🔎 Type-checking a minimal consumer against dist/agentlet-core.d.ts...');
    const result = spawnSync(tscBin, tscArgs, { stdio: 'inherit' });

    if (result.error) {
        fail(`Failed to run tsc: ${result.error.message}`);
    }

    if (result.status !== 0) {
        fail('dist/agentlet-core.d.ts failed to type-check against the minimal consumer above.');
    }

    console.log('✅ dist/agentlet-core.d.ts loads and type-checks correctly.');
} finally {
    rmSync(tmpDir, { recursive: true, force: true });
}
